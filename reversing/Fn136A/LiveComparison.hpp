// Dos funciones del EXE con contrato __usercall (caracter en AL, dos punteros de salida en la pila, `ret` sin limpiar la pila), cada una con 16384 pares EXE/DLL: 0x6FD7C0 (columna y fila
// del caracter en la plantilla de matriculas) y 0x6FE260 (id. en la plantilla de carteles de carretera). Hook S (RH_ScopedGlobalInstall: enlace de la entrada del EXE hacia la DLL).
// El banco invoca la direccion del EXE con EAX = basura en los 24 bits altos y el caracter en AL, y los dos punteros en arenas propias (A, B y C con guardas de 0x40).
// Sin colaboradores y sin memoria global del juego. Se observan los bytes cambiados de las tres arenas y el estado x87 (debe quedar vacio); EAX/ECX/EDX tras la llamada quedan en
// original_residue / candidate_residue (informativos: ningun llamador los lee).

