// RwMatrixDestroy (0x7F2A20; cdecl, un puntero): evento [direccion, puntero (etiqueta)]. No lee nada. Devuelve 1.
inline u32 __cdecl FkDestroy(void* p) { Ev& e = PushEv(0x7F2A20, 1); e.v[0] = Tag(p); return 1; }

// ================================================================================================ cierre de un lado
inline json CloseSide(Env& env, Side& side, json obs) {
    auto fp = NormalizeFp(side.fp);
    obs["globals_hash"] = RegionsHash();
    json out = CommonRow(side, fp); out["observed"] = obs;
    RestoreFloatingState();
    RestoreRegions();
    out["globals_restored"] = env.WatchesIntact() && RegionsIntact();
    out["floating_state_restored"] = FloatingStateRestored();
    return out;
}

// Descripcion de la llamada de un caso
struct Call {
    std::array<u32, 8> args{};
    u32 argCount{}, popBytes{}, ecx{};
};

// Prepara arenas del caso; devuelve la llamada
inline Call Setup(const C& c) {
    Call call; call.ecx = c.ecx;
    const auto& a = c.a;
    arenaA.Pattern(a[2], a[12]); arenaB.Pattern(a[2], a[13]); arenaC.Pattern(a[2], a[14]);
    const u32 thisA = u32(arenaA.Obj(a[0]));
    call.ecx = thisA;
    const Kind k = kKind[c.fn];
    const u32 dstBytes = k == kV2 ? 8u : 0x40u;
    // destino inicial de this
    arenaA.PutBytes(a[0], c.s.data() + 64, dstBytes);
    u32 src = 0;
    if (kSrcSpan[c.fn]) {
        switch (a[3]) {
        case 0: src = u32(arenaB.Obj(a[4])); arenaB.PutBytes(a[4], c.s.data(), kSrcSpan[c.fn]); break;
        case 1: src = u32(arenaC.Obj(a[4])); arenaC.PutBytes(a[4], c.s.data(), kSrcSpan[c.fn]); break;
        case 2: src = u32(arenaA.Obj(a[4])); arenaA.PutBytes(a[4], c.s.data(), kSrcSpan[c.fn]); break;
        default: src = thisA; break;
        }
    }
    switch (k) {
    case kUpd:
        arenaA.Put32(a[0] + 0x40, src); arenaA.Put32(a[0] + 0x44, a[5]);
        break;
    case kDetach:
        arenaA.Put32(a[0] + 0x40, a[3] == 0 ? 0u : (a[3] == 1 ? u32(arenaB.Obj(a[4])) : a[5])); arenaA.Put32(a[0] + 0x44, a[6]);
        break;
    case kScale:
        call.args[0] = a[3]; call.argCount = 1; call.popBytes = 0;
        break;
    default:   // kUpdArg, kCopy, kAdd, kV2: un puntero de pila (`ret 4`)
        call.args[0] = src; call.argCount = 1; call.popBytes = 0;
        break;
    }
    return call;
}

inline void CaseRun(Env& env, Totals& t, unsigned fn, unsigned n) {
    const C c = MakeC(fn, n);
    json input = json::parse(JsonC(c));
    input["arena"] = json::array({u32(uintptr_t(arenaA.m.data())), u32(uintptr_t(arenaB.m.data())), u32(uintptr_t(arenaC.m.data()))});   // direcciones reales de las arenas (para el oraculo)
    Side sides[2]; json rows[2];
    curFn = fn;
    for (int s = 0; s < 2; ++s) {
        const bool candidate = s == 1;
        PrepareFloatingState();
        const Call call = Setup(c);
        arenaA.Snap(); arenaB.Snap(); arenaC.Snap();
        TagClear(); TagAdd(arenaA.m.data(), arenaA.m.size()); TagAdd(arenaB.m.data(), arenaB.m.size()); TagAdd(arenaC.m.data(), arenaC.m.size());
        nev = 0;
        sides[s] = Execute(env, fn, kEntries[fn], candidate, [&](uintptr_t entry) {
            return Gate(entry, call.args.data(), call.argCount, c.eax, call.ecx, c.edx, c.stack, call.popBytes);
        });
        json obs;
        obs["changes"] = {{"A", arenaA.Changes()}, {"B", arenaB.Changes()}, {"C", arenaC.Changes()}};
        obs["gchanges"] = json::array();
        obs["events"] = EvsJson();
        const u32 eax = sides[s].reg.eax;
        switch (kKind[fn]) {
        case kV2: obs["ret"] = Tag(uintptr_t(eax)); break;   // this como etiqueta de arena
        default: obs["ret"] = nullptr; break;                // void
        }
        rows[s] = CloseSide(env, sides[s], obs);
    }
    Finish(t, kFn[fn], n, input, rows, sides);
}


