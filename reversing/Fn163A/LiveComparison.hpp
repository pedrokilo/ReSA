// Banco par a par Fn163A dentro del juego: Update() se llama desde CGame::Process (probe_build.py). Todo el nucleo esta en Core.hpp.
// Cuatro cuerpos de destructor de tareas del EXE (CTaskSimpleTriggerLookAt 0x634500, CTaskComplexObserveTrafficLightsAndAchieveHeading 0x631980, CTaskComplexDieInCar 0x62FCF0 y CTaskSimpleSwim 0x688A00; ver Fixtures.hpp),
// cada uno con 16384 pares EXE/DLL. Hook S (RH_ScopedNamedGlobalInstall). El banco invoca la direccion del EXE con objetos sinteticos en arenas propias (A, B, C con guardas de 0x40). Falsos de los colaboradores
// (todos con hook RH en la DLL, apagado durante el banco): el mismo falso en la direccion del EXE y en el cuerpo de la DLL (MakeCollab): CEntity::CleanUpOldReference 0x571A00, ~CTask 0x61A3A0, ~CTaskComplex 0x61A3D0
// y CAnimManager::RemoveAnimBlockRef 0x4D3FD0. El cuerpo de Swim lee el puntero global ms_aAnimAssocGroups (0xB4EA34): el banco lo apunta a una tabla falsa de la arena C durante la llamada y lo restaura (Region).
// Se observan: los bytes cambiados de las tres arenas, los eventos de los falsos (con sus argumentos) y el estado x87 (siempre vacio). EAX/ECX/EDX tras la llamada quedan en original_residue / candidate_residue (informativos).

