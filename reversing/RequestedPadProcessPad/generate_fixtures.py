"""Deterministic corpus generator for the ProcessPad bank. Writes fixtures.json and Fixtures.hpp.
Single source of truth for model.py (Python) and LiveComparison.hpp (C++). No game, no compiler."""
import hashlib, itertools, json
from pathlib import Path
HERE = Path(__file__).resolve().parent
FIELDS = ['route', 'pad', 'padnum', 'justinit', 'flip', 'pc', 'joymask', 'menu', 'poison', 'lx', 'ly', 'lz', 'lrz', 'pov']
NOPOV = 0xFFFFFFFF   # low word 0xFFFF: POV branch skipped (neutral)
I32MIN, I32MAX = -2147483648, 2147483647
ROUTES = 11          # 0 slot null .. 10 acquire S_FALSE (see corpus-plan.json)
POISONS = (0x00, 0x55, 0xAA, 0xFF)
PC24, PC53 = 0, 1
S0 = (0, 0, 0, 0, NOPOV)
S1 = (1200, -1500, 900, -700, 4500)
S2 = (601, -601, 601, -601, NOPOV)
CURATED = [(0, 0, 0, 0), (600, 600, 600, 600), (601, 601, 601, 601), (-600, -600, -600, -600), (-601, -601, -601, -601),
           (1000, -1000, 1000, -1000), (2000, 500, -2000, -500), (599, 601, -599, -601), (32767, -32768, 32767, -32768),
           (65535, -65535, 1, -1), (I32MAX, I32MIN, I32MIN, I32MAX), (16777217, -16777219, 300, -300)]
BOUND = [0, 1, -1, 299, 300, 599, 600, 601, -599, -600, -601, 700, -700, 1000, -1000, 2000, -2000, 65535, -65536, 16777217, I32MAX, I32MIN]
# POV values with low word != 0xFFFF; values >= 0x80000000 exercise the EXE fadd 2^32 rounding path.
POV_ACTIVE = [0, 1, 4500, 9000, 13500, 18000, 22500, 27000, 31500, 35999, 36000, 65534, 0x00010000, 0x00123456, 0x01000001, 0x7FFF0000,
              0x7FFFFFFE, 0x80000000, 0x80000001, 0x80001234, 0x8000FFFE, 0x80FF0000, 0xC0000000, 0xFFFE0000, 0xFFFF0000, 0xFFFF0001, 0xFFFFFFFE, 0xDEADBEEF,
              0xFED4D57B, 0xF311D8A3, 0xF8E51061, 0xE12E7696, 0x98072E8C, 0x8741C7A8, 0x808A05A6, 0x825B413F]   # last 8: PC24 fadd rounding changes the sine in the exact-double model
POV_SKIP = [0xFFFF, 0x0001FFFF, 0x7FFFFFFF, 0xFFFFFFFF, 0x8000FFFF]
rows = []
def add(route, pad, padnum, justinit, flip, pc, joymask, menu, poison, stick):
    lx, ly, lz, lrz = stick[:4]
    pov = stick[4] if len(stick) > 4 else NOPOV
    rows.append((route, pad, padnum, justinit, flip, pc, joymask, menu, poison, lx, ly, lz, lrz, pov))
# P1 route sweep
for route, pad, padnum, ji, pc, poison, s, jm in itertools.product(range(ROUTES), (0, 1), (0, 1, 255), (0, 1), (PC24, PC53), (0x00, 0xAA), (S0, S1, S2), (3, 0)):
    add(route, pad, padnum, ji, 0, pc, jm, 0b010101 if route % 2 else 0b101010, poison, s)
# P2 side-effect sweep on the success route: flip kinds 1..4
for flip, pad, padnum, ji, pc, jm, s, menu in itertools.product((1, 2, 3, 4), (0, 1), (0, 1), (0, 1), (PC24, PC53), (0, 1, 2, 3), (S1, S2), (0, 0b001111, 0b110000)):
    add(1, pad, padnum, ji, flip, pc, jm, menu, POISONS[(flip + pad + padnum) % 4], s)
# P3 stick matrix: 64 menu flag combos x 4 joy masks x curated stick vectors x pads (PC24) + sampled menus at PC53
for menu, jm, v, pad in itertools.product(range(64), range(4), CURATED, (0, 1)):
    add(1, pad, (menu + jm) % 2, (menu + v[0]) % 2, 0, PC24, jm, menu, POISONS[(menu + jm + pad) % 4], v + (NOPOV,))
for menu, jm, v, pad in itertools.product((0, 21, 42, 63, 5, 10, 48, 15), range(4), CURATED, (0, 1)):
    add(1, pad, 0, 0, 0, PC53, jm, menu, POISONS[(menu + pad) % 4], v + (NOPOV,))
# P4 single-axis boundary sweep
for axis, value, menu, jm, pad, pc in itertools.product(range(4), BOUND, (0, 63, 21, 42), (3, 1), (0, 1), (PC24, PC53)):
    v = [0, 0, 0, 0]; v[axis] = value
    add(1, pad, 0, pad, 0, pc, jm, menu, POISONS[axis], tuple(v) + (NOPOV,))
# P5 POV sweep (left stick replaced by sine/cosine; right stick raw)
for pov, base, menu, pad, pc in itertools.product(POV_ACTIVE + POV_SKIP, ((0, 0, 700, -700), (1200, -1500, 0, 0)), (0, 63, 17, 34), (0, 1), (PC24, PC53)):
    add(1, pad, 0, 1 - pad, 0, pc, 3, menu, POISONS[pov % 4], base + (pov,))
# P6 deterministic pseudo-random stick/POV vectors (LCG documented in README)
state = 0x1F2E3D4C
def rnd():
    global state
    state = (state * 1103515245 + 12345) & 0x7FFFFFFF
    return state
def axis():
    k = rnd() % 10
    if k < 6: return rnd() % 3001 - 1500
    if k < 8: return rnd() % 80001 - 40000
    if k == 8: return (rnd() << 1 ^ rnd()) % (2 ** 32) - 2 ** 31
    return [I32MAX, I32MIN, 16777217, -16777217, 600, -600][rnd() % 6]
for n in range(1536):
    pov = NOPOV if rnd() % 3 == 0 else (rnd() % 36001 if rnd() % 2 else ((rnd() << 16) ^ rnd()) & 0xFFFFFFFF)
    if pov & 0xFFFF == 0xFFFF and rnd() % 2: pov ^= 1
    add(1, rnd() % 2, [0, 1, 255][rnd() % 3], rnd() % 2, [0, 0, 0, 1, 2, 3, 4][rnd() % 7], rnd() % 2, rnd() % 4, rnd() % 64, POISONS[rnd() % 4], (axis(), axis(), axis(), axis(), pov))
seen = set(); unique = []
for r in rows:
    if r not in seen: seen.add(r); unique.append(r)
rows = unique
def c32(v): return '(-2147483647-1)' if v == I32MIN else str(v)
text = ['#pragma once', '// Generated by generate_fixtures.py. Do not edit.', 'namespace RequestedPadProcessPad {',
        'struct Fixture{uint8 route,pad,padnum,justinit,flip,pc,joymask,menu,poison;int32 lx,ly,lz,lrz;uint32 pov;};',
        f'inline constexpr unsigned kFixtureCount={len(rows)};', 'inline constexpr Fixture fixtures[kFixtureCount]={']
for r in rows: text.append('{' + ','.join(list(map(str, r[:9])) + [c32(r[9]), c32(r[10]), c32(r[11]), c32(r[12]), f'{r[13]}u']) + '},')
text += ['};', '}', '']
(HERE / 'Fixtures.hpp').write_text('\n'.join(text), encoding='utf8', newline='\n')
doc = {'fields': FIELDS, 'count': len(rows), 'rows': [list(r) for r in rows]}
(HERE / 'fixtures.json').write_text(json.dumps(doc, separators=(',', ':')) + '\n', encoding='utf8', newline='\n')
print(len(rows), hashlib.sha256((HERE / 'fixtures.json').read_bytes()).hexdigest())
